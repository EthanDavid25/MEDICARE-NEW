import React from "react";
import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  TouchableOpacity,
  Share,
  Platform
} from "react-native";
import { Colors } from "../theme/colors";
import { Typography } from "../theme/typography";
import { Spacing } from "../theme/spacing";
import { Card } from "../components/common/Card";
import { Button } from "../components/common/Button";
import { AssessmentResult } from "../../shared/types";

interface AssessmentResultsScreenProps {
  route: {
    params: {
      result: AssessmentResult;
    };
  };
  navigation: any;
}

export const AssessmentResultsScreen: React.FC<AssessmentResultsScreenProps> = ({
  route,
  navigation
}) => {
  const { result } = route.params;

  const getCategoryTheme = () => {
    switch (result.category.toLowerCase()) {
      case "emergency":
        return {
          bannerBg: Colors.emergency,
          badgeBg: "#7F1D1D",
          tagText: "CRITICAL ALERT",
          title: "EMERGENCY EVALUATION REQUIRED",
          sub: "Seek immediate emergency medical attention or call 112 / 108 right away.",
          accentColor: Colors.emergency
        };
      case "urgent":
        return {
          bannerBg: Colors.urgent,
          badgeBg: "#78350F",
          tagText: "HIGH PRIORITY",
          title: "URGENT MEDICAL ATTENTION",
          sub: "Consult a qualified physician or urgent care center within 4 to 12 hours.",
          accentColor: Colors.urgent
        };
      case "routine":
        return {
          bannerBg: Colors.blueAccent,
          badgeBg: Colors.navyPrimary,
          tagText: "CLINICAL EVALUATION",
          title: "ROUTINE CLINICAL CARE",
          sub: "Schedule an appointment with your primary care provider within 24 to 48 hours.",
          accentColor: Colors.blueAccent
        };
      default:
        return {
          bannerBg: Colors.selfCare,
          badgeBg: "#064E3B",
          tagText: "HOME CARE",
          title: "SUPPORTIVE SELF-CARE",
          sub: "Manage symptoms with rest and hydration. Seek medical review if symptoms worsen.",
          accentColor: Colors.selfCare
        };
    }
  };

  const theme = getCategoryTheme();

  // Strip technical rule IDs like "RULE_004", "SEV_09" from explanations if any
  const cleanClinicalExplanation = (text: string) => {
    return text
      .replace(/\[?RULE_[A-Z0-9_-]+\]?/gi, "")
      .replace(/\[?SEV_[A-Z0-9_-]+\]?/gi, "")
      .replace(/\s{2,}/g, " ")
      .trim();
  };

  const handleShare = async () => {
    try {
      const summary = `MEDICARE TRIAGE REPORT\nCategory: ${result.category.toUpperCase()}\nChief Complaint: ${result.chief_symptom.replace(/_/g, " ")}\nSeverity: ${result.severity_score}/10\nUrgency: ${result.recommended_action}\nGenerated by MEDICARE Mobile`;
      await Share.share({
        message: summary,
        title: "MEDICARE Triage Summary"
      });
    } catch (err) {
      console.warn("Share failed", err);
    }
  };

  return (
    <View style={styles.container}>
      <ScrollView contentContainerStyle={styles.scrollContent} showsVerticalScrollIndicator={false}>
        {/* TOP STATUS BANNER */}
        <View style={[styles.topBanner, { backgroundColor: theme.bannerBg }]}>
          <View style={[styles.tagBadge, { backgroundColor: theme.badgeBg }]}>
            <Text style={styles.tagText}>{theme.tagText}</Text>
          </View>
          <Text style={styles.bannerTitle}>{theme.title}</Text>
          <Text style={styles.bannerSub}>{theme.sub}</Text>
          <View style={styles.metaRow}>
            <Text style={styles.metaText}>Severity Score: {result.severity_score}/10</Text>
            <Text style={styles.metaText}>•</Text>
            <Text style={styles.metaText}>
              {new Date(result.timestamp).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}
            </Text>
          </View>
        </View>

        {/* CLINICAL SUMMARY CARD */}
        <Card style={styles.contentCard} variant="elevated">
          <Text style={styles.sectionHeader}>Clinical Impression</Text>
          <View style={styles.symptomHighlight}>
            <Text style={styles.symptomHighlightLabel}>Chief Complaint:</Text>
            <Text style={styles.symptomHighlightValue}>
              {result.chief_symptom.replace(/_/g, " ").toUpperCase()}
            </Text>
          </View>

          <Text style={styles.recommendationText}>{result.recommended_action}</Text>

          {/* Clinical Reasoning (Cleaned of raw rule IDs) */}
          <View style={styles.reasoningBox}>
            <Text style={styles.reasoningTitle}>Clinical Rationale:</Text>
            <Text style={styles.reasoningText}>
              {cleanClinicalExplanation(result.explanation)}
            </Text>
          </View>

          {/* Matched Danger Signs / Rules if present */}
          {result.matched_rules && result.matched_rules.length > 0 && (
            <View style={styles.matchedSection}>
              <Text style={styles.matchedTitle}>Key Clinical Findings:</Text>
              {result.matched_rules.map((rule, idx) => (
                <View key={`mr-${idx}`} style={styles.matchedItem}>
                  <Text style={styles.matchedBullet}>•</Text>
                  <Text style={styles.matchedText}>
                    {cleanClinicalExplanation(rule.description || rule.name || rule.rule_id || "")}
                  </Text>
                </View>
              ))}
            </View>
          )}

          {/* Single clean missing info notice if any */}
          {result.missing_critical_info && result.missing_critical_info.length > 0 && (
            <View style={styles.missingNotice}>
              <Text style={styles.missingTitle}>ℹ️ Assessment Note:</Text>
              <Text style={styles.missingText}>
                Clinical baseline evaluation completed. Objective vitals (Blood Pressure, SpO2) were not measured and should be verified upon facility arrival.
              </Text>
            </View>
          )}
        </Card>

        {/* IMMEDIATE ACTION GUIDANCE */}
        <Card style={styles.guidanceCard}>
          <Text style={styles.guidanceTitle}>Recommended Next Steps</Text>
          <View style={styles.guidanceStep}>
            <Text style={styles.stepNumber}>1</Text>
            <Text style={styles.stepText}>
              {result.category.toLowerCase() === "emergency"
                ? "Do not drive yourself. Request an ambulance (108/112) or have a family member transport you immediately."
                : "Proceed to an appropriate healthcare facility or consult your family physician."}
            </Text>
          </View>
          <View style={styles.guidanceStep}>
            <Text style={styles.stepNumber}>2</Text>
            <Text style={styles.stepText}>
              Present the Doctor Handover Summary to the triage nurse or attending doctor upon arrival.
            </Text>
          </View>
          <View style={styles.guidanceStep}>
            <Text style={styles.stepNumber}>3</Text>
            <Text style={styles.stepText}>
              If symptoms suddenly worsen or new danger signs develop, call 112 immediately.
            </Text>
          </View>
        </Card>

        {/* PRIMARY ACTION BUTTONS */}
        <View style={styles.actionsContainer}>
          <Button
            title="🏥 Find Nearby Hospitals"
            onPress={() => navigation.navigate("Hospitals")}
            variant="primary"
            size="large"
            style={styles.actionBtn}
          />

          <Button
            title="📋 View Doctor Handover"
            onPress={() => navigation.navigate("DoctorHandover", { result })}
            variant="outline"
            size="large"
            style={styles.actionBtn}
          />

          <Button
            title="Share Summary"
            onPress={handleShare}
            variant="secondary"
            size="medium"
            style={styles.actionBtn}
          />

          <TouchableOpacity
            style={styles.homeLink}
            onPress={() => navigation.navigate("Dashboard")}
          >
            <Text style={styles.homeLinkText}>Return to Home Dashboard</Text>
          </TouchableOpacity>
        </View>
      </ScrollView>
    </View>
  );
};

