"""
MEDICARE Patient Profile Management Service.
Handles local patient registration, profile updates, retrieval, deletion, and local JSON export.
All patient data is stored locally in SQLite with zero external cloud transmission.
"""
import json
import logging
from typing import Optional
from datetime import datetime

logger = logging.getLogger("medicare.patients")

class PatientService:
    def __init__(self, db):
        self.db = db

    def create_patient(self, profile: dict) -> int:
        """Creates a new patient profile. Returns new patient ID."""
        now = datetime.now().isoformat()
        data = {
            "display_name": profile.get("display_name", "").strip(),
            "date_of_birth": profile.get("date_of_birth", ""),
            "biological_sex": profile.get("biological_sex", "prefer_not_to_say"),
            "blood_group": profile.get("blood_group", ""),
            "known_allergies": profile.get("known_allergies", ""),
            "chronic_conditions": profile.get("chronic_conditions", ""),
            "current_medications": profile.get("current_medications", ""),
            "emergency_contact": profile.get("emergency_contact", ""),
            "created_at": now,
            "updated_at": now,
            "is_deleted": 0
        }
        patient_id = self.db.insert("patients", data)
        self.db.log_audit_event("PATIENT_CREATED", f"Patient ID {patient_id} registered")
        return patient_id

    def update_patient(self, patient_id: int, profile: dict) -> bool:
        """Updates an existing patient profile."""
        data = {
            "display_name": profile.get("display_name", "").strip(),
            "date_of_birth": profile.get("date_of_birth", ""),
            "biological_sex": profile.get("biological_sex", "prefer_not_to_say"),
            "blood_group": profile.get("blood_group", ""),
            "known_allergies": profile.get("known_allergies", ""),
            "chronic_conditions": profile.get("chronic_conditions", ""),
            "current_medications": profile.get("current_medications", ""),
            "emergency_contact": profile.get("emergency_contact", ""),
            "updated_at": datetime.now().isoformat()
        }
        rows = self.db.update("patients", data, "id = ?", (patient_id,))
        self.db.log_audit_event("PATIENT_UPDATED", f"Patient ID {patient_id} updated")
        return rows > 0

    def get_patient(self, patient_id: int) -> Optional[dict]:
        """Retrieves a single patient profile by ID."""
        return self.db.fetchone("SELECT * FROM patients WHERE id = ? AND is_deleted = 0", (patient_id,))

    def get_all_patients(self) -> list[dict]:
        """Returns list of active patient profiles."""
        return self.db.fetchall("SELECT * FROM patients WHERE is_deleted = 0 ORDER BY display_name ASC")

    def delete_patient(self, patient_id: int, hard_delete: bool = False) -> bool:
        """Deletes a patient record (soft delete by default, or full hard delete with confirmation)."""
        if hard_delete:
            self.db.execute("DELETE FROM symptom_history WHERE patient_id = ?", (patient_id,))
            self.db.execute("DELETE FROM symptom_entries WHERE patient_id = ?", (patient_id,))
            self.db.execute("DELETE FROM assessments WHERE patient_id = ?", (patient_id,))
            self.db.execute("DELETE FROM patients WHERE id = ?", (patient_id,))
            self.db.log_audit_event("PATIENT_HARD_DELETED", f"Patient ID {patient_id} permanently erased")
        else:
            self.db.execute("UPDATE patients SET is_deleted = 1, updated_at = datetime('now') WHERE id = ?", (patient_id,))
            self.db.log_audit_event("PATIENT_SOFT_DELETED", f"Patient ID {patient_id} soft deleted")
        return True

    def export_patient_data(self, patient_id: int) -> dict:
        """Exports complete patient record, assessment history, and symptom timeline as structured JSON."""
        patient = self.get_patient(patient_id)
        if not patient:
            return {}
        assessments = self.db.fetchall(
            "SELECT * FROM assessments WHERE patient_id = ? AND is_deleted = 0 ORDER BY completed_at DESC", 
            (patient_id,)
        )
        symptoms = self.db.fetchall(
            "SELECT * FROM symptom_history WHERE patient_id = ? ORDER BY recorded_at DESC", 
            (patient_id,)
        )
        return {
            "medicare_export_version": "1.0.0",
            "exported_at": datetime.now().isoformat(),
            "patient_profile": patient,
            "assessments": assessments,
            "symptom_history": symptoms,
            "disclaimer": "This document contains sensitive personal health information generated by MEDICARE."
        }
